/**
 * Builds the official NPCI UPI payment URI string.
 * NOTE: Payee address (`pa`) MUST contain the literal `@` symbol and must NOT
 * be percent-encoded to `%40`, as UPI mobile scanners strictly parse the literal VPA.
 *
 * @param {Object} config
 * @param {string} config.vpa - UPI Virtual Payment Address (e.g. 'merchant@okaxis')
 * @param {string} config.payeeName - Registered Name (e.g. 'InvoZap Solutions')
 * @param {number|string} config.amount - Rupee amount (e.g. 22420 or '22420.00')
 * @param {string} config.invoiceNumber - Invoice / Reference Number (e.g. 'INV/2026-27/0001')
 * @returns {string} UPI deep-link URI
 */
function buildUpiUri({ vpa, payeeName = "InvoZap Merchant", amount = 0, invoiceNumber = "INV" }) {
  if (!vpa || !vpa.trim()) return "";

  const cleanVpa = vpa.trim();
  const cleanPayee = (payeeName || "Merchant").replace(/[^a-zA-Z0-9 ]/g, "").trim();
  const numAmount = typeof amount === "number" ? amount : parseFloat(String(amount).replace(/[^0-9.]/g, "")) || 0;
  const formattedAmount = numAmount.toFixed(2);
  // NPCI tn rule: Alphanumeric and hyphens only, no slashes or encoded %2F
  const cleanRef = (invoiceNumber || "INV").replace(/[\/\\]/g, "-").replace(/[^a-zA-Z0-9 -]/g, "").trim();

  // NPCI Standard Query Parameters (preserving literal @ in pa)
  const encodedPayee = encodeURIComponent(cleanPayee);
  const encodedRef = encodeURIComponent(cleanRef);

  return `upi://pay?pa=${cleanVpa}&pn=${encodedPayee}&am=${formattedAmount}&cu=INR&tn=${encodedRef}`;
}

